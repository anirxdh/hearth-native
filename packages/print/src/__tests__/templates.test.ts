describe('escaping', () => {
  const hostilePatient: PrintPatient = {
    fullName: '<script>alert("x")</script> O\'Brien & Sons',
    conditions: ['A > B < C'],
    allergies: [{ name: 'Sulfa "drugs"', reaction: "Hives & swelling of the throat, worse when it's hot", severe: true }],
  };

  const html = onePagerHtml({
    patient: hostilePatient,
    meds: [],
    vitals: [],
    contacts: [],
    nutrition: [],
    generatedAt: GENERATED_AT,
  });

  test('neutralizes a script tag in the patient name', () => {
    expect(html).not.toContain('<script>');
    expect(html).not.toContain('</script>');
    expect(html).toContain('&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;');
  });

  test('escapes ampersands, angle brackets, and both quote styles', () => {
    expect(html).toContain('O&#39;Brien &amp; Sons');
    expect(html).toContain('A &gt; B &lt; C');
    expect(html).toContain('Sulfa &quot;drugs&quot;');
    expect(html).toContain('worse when it&#39;s hot');
  });
});
